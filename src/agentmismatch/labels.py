"""Token span labels.

Every token in a trajectory gets exactly one label. The core comparison of the
paper is ACTION tokens (TOOL_NAME, TOOL_ARGS, ACTION_OTHER) versus REASONING
tokens. ENV tokens are not generated by the policy (tool outputs, chat-template
scaffolding we insert) and are never trained on.
"""

from enum import IntEnum


class Label(IntEnum):
    ENV = 0           # not produced by the policy (prompt, tool responses, inserted template text)
    REASONING = 1     # thinking / free text
    TOOL_NAME = 2     # the value of "name" inside a tool call
    TOOL_ARGS = 3     # the value of "arguments" inside a tool call
    ACTION_OTHER = 4  # JSON scaffolding inside <tool_call>...</tool_call>
    ANSWER = 5        # the final \boxed{...} answer
    FORMAT = 6        # special/control tokens: <think>, </tool_call>, <|im_end|>, ...


ACTION_LABELS = frozenset({Label.TOOL_NAME, Label.TOOL_ARGS, Label.ACTION_OTHER})
POLICY_LABELS = frozenset(Label) - {Label.ENV}
